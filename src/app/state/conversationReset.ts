import type { AppState } from "@/app/state/types";

export function buildConversationResetState(
	state: AppState,
	options: { preserveWorkerContext?: boolean; preserveVoiceSession?: boolean } = {},
): AppState {
	const preserveWorkerContext = Boolean(options.preserveWorkerContext);
	const stableRightSidebarTab =
		state.rightSidebarOpenTab === "overview" ||
		state.rightSidebarOpenTab === "debug"
			? state.rightSidebarOpenTab
			: null;
	return {
		...state,
		currentChatActiveRun: null,
		editingMode: undefined,
		runId: "",
		currentRunAgentKey: "",
		pendingNewChatAgentKey: "",
		requestId: "",
		streaming: false,
		abortController: null,
		messagesById: new Map(),
		messageOrder: [],
		events: [],
		debugEvents: [],
		artifacts: [],
		fileChanges: [],
		plan: null,
		planRuntimeByTaskId: new Map(),
		taskItemsById: new Map(),
		activeTaskIds: new Set(),
		planCurrentRunningTaskId: "",
		planLastTouchedTaskId: "",
		artifactExpanded: false,
		artifactManualOverride: null,
		artifactAutoCollapseTimer: null,
		planExpanded: false,
		planManualOverride: null,
		planAutoCollapseTimer: null,
		toolStates: new Map(),
		toolNodeById: new Map(),
		contentNodeById: new Map(),
		pendingTools: new Map(),
		reasoningNodeById: new Map(),
		reasoningCollapseTimers: new Map(),
		actionStates: new Map(),
		executedActionIds: new Set(),
		timelineNodes: new Map(),
		timelineOrder: [],
		timelineNodeByMessageId: new Map(),
		timelineDomCache: new Map(),
		timelineCounter: 0,
		renderQueue: {
			dirtyNodeIds: new Set(),
			scheduled: false,
			stickToBottomRequested: false,
			fullSyncNeeded: false,
		},
		activeReasoningKey: "",
		activeFrontendTool: null,
		activeAwaiting: null,
		pendingAwaitings: [],
		usageSnapshot: null,
		usageRefreshFailed: false,
		usagePopoverOpen: false,
		rightSidebarOpenTab: stableRightSidebarTab,
		activeSourceDetail: null,
		planningPreviews: [],
		webPreviews: [],
		webPreviewRefreshRevisionByUrl: new Map(),
		activeWebPreviewUrl: "",
		viewPreviews: [],
		activeViewPreviewKey: "",
		viewerTabs: [],
		documentPreviewTabs: [],
		activeDocumentPreviewKey: "",
		activeViewerKey: "",
		inputMode: options.preserveVoiceSession ? state.inputMode : "text",
		voiceChat: options.preserveVoiceSession ? state.voiceChat : {
			...state.voiceChat,
			status: "idle",
			sessionActive: false,
			partialUserText: "",
			partialAssistantText: "",
			error: "",
			awaiting: false,
			currentAgentKey: "",
			currentAgentName: "",
		},
		workerRelatedChats: preserveWorkerContext ? state.workerRelatedChats : [],
		workerChatPanelCollapsed: preserveWorkerContext
			? state.workerChatPanelCollapsed
			: true,
		pendingSteers: state.pendingSteers,
		downvotedRunKeys: new Set(),
		eventPopoverIndex: -1,
		eventPopoverEventRef: null,
		eventPopoverAnchor: null,
		commandStatusOverlay: {
			visible: false,
			commandType: null,
			phase: "success",
			text: "",
			timer: null,
		},
	};
}
